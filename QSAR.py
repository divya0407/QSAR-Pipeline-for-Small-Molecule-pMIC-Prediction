def evaluate_model(name, base_model, param_grid):
    print("\n" + "="*70)
    print(f"Training model: {name}")
    print("="*70)

    # pipeline
    steps = [
        ("imputer", SimpleImputer(strategy="median")),
        ("var", VarianceThreshold(0.0)),
        ("scaler", StandardScaler()),
    ]

    # RFE only for Ridge (good QSAR approach)
    if name == "Ridge_RFE":
        steps.append(("rfe", RFE(estimator=Ridge(alpha=1.0))))
    else:
        steps.append(("rfe", "passthrough"))

    steps.append(("model", base_model))

    pipe = Pipeline(steps)

    grid = GridSearchCV(
        pipe,
        param_grid=param_grid,
        scoring="neg_root_mean_squared_error",
        cv=loo,
        n_jobs=-1
    )

    grid.fit(X_train_corr, y)

    best_model = grid.best_estimator_

    y_pred_cv = cross_val_predict(best_model, X_train_corr, y, cv=loo, n_jobs=-1)

    rmse = np.sqrt(mean_squared_error(y, y_pred_cv))
    mae = mean_absolute_error(y, y_pred_cv)
    q2 = r2_score(y, y_pred_cv)

    print("Best params:", grid.best_params_)
    print(f"Q2 (LOOCV R2): {q2:.3f}")
    print(f"RMSEcv       : {rmse:.3f}")
    print(f"MAEcv        : {mae:.3f}")

    return best_model, q2, rmse, mae

