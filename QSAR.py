calc = Calculator(descriptors, ignore_3D=True)

def compute_descriptors(df, smiles_col):

    mols = []
    valid_idx = []

    for i, smi in enumerate(df[smiles_col].astype(str)):

        mol = Chem.MolFromSmiles(smi)

        if mol is not None:
            mols.append(mol)
            valid_idx.append(i)

    desc = calc.pandas(mols, nproc=1)

    desc = desc.apply(
        pd.to_numeric,
        errors="coerce"
    )

    return valid_idx, desc


