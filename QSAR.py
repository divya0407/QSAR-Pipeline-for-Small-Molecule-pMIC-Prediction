def y_randomization(X, y, model, n_iter=50, seed=42):
    rng = np.random.RandomState(seed)
    q2_list = []

    for i in range(n_iter):
        y_shuff = rng.permutation(y)
        y_pred_shuff = cross_val_predict(model, X, y_shuff, cv=loo, n_jobs=-1)
        q2 = r2_score(y_shuff, y_pred_shuff)
        q2_list.append(q2)

    return np.array(q2_list)

