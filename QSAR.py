def remove_correlated_features(X, threshold=0.90):

    corr = X.corr().abs()

    upper = corr.where(
        np.triu(np.ones(corr.shape), k=1).astype(bool)
    )

    to_drop = [
        col for col in upper.columns
        if any(upper[col] > threshold)
    ]

    return X.drop(columns=to_drop), to_drop


