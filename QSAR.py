# Apply this mask to the columns of X_train_corr to get column names after VarianceThreshold
# X_train_corr is the training data after initial correlation filtering, and it's what
# the final_model was fit on (after its internal preprocessing steps).
columns_after_var = X_train_corr.columns[var_mask]

# Now, apply the RFE selection mask to these columns
selected_mask = final_model.named_steps["rfe"].support_
selected_features = columns_after_var[selected_mask]

top10_df = pd.DataFrame({
    "Top_10_Descriptors": selected_features
})

top10_df.to_csv("Top10_Selected_Descriptors.csv", index=False)
print("Saved: Top10_Selected_Descriptors.csv")


# ============================================================
# 2) Predict pMIC for test compounds
# ============================================================

test_pred_pmic = final_model.predict(X_test_corr)

test_pred_df = pd.DataFrame({
    "Test_Compound": np.arange(1, len(test_pred_pmic)+1),
    "Predicted_pMIC": test_pred_pmic
})

test_pred_df.to_csv("Test_Predicted_pMIC.csv", index=False)
print("Saved: Test_Predicted_pMIC.csv")


# ============================================================
# 3) Convert predicted pMIC → MIC (µM)
# ============================================================
# pMIC = -log10(MIC in M)
# MIC(M) = 10^(-pMIC)
# MIC(µM) = 10^(-pMIC) * 1e6

test_pred_df["Predicted_MIC_uM"] = (10 ** (-test_pred_df["Predicted_pMIC"])) * 1e6

# Optional rounding
test_pred_df["Predicted_MIC_uM"] = test_pred_df["Predicted_MIC_uM"].round(4)
test_pred_df["Predicted_pMIC"] = test_pred_df["Predicted_pMIC"].round(4)

# Save MIC file
test_pred_df[["Test_Compound", "Predicted_MIC_uM"]].to_csv("Test_Predicted_MIC_uM.csv", index=False)
print("Saved: Test_Predicted_MIC_uM.csv")


# ============================================================
# 4) Save combined file (pMIC + MIC)
# ============================================================

test_pred_df.to_csv("Test_Predicted_pMIC_and_MIC.csv", index=False)
print("Saved: Test_Predicted_pMIC_and_MIC.csv")

